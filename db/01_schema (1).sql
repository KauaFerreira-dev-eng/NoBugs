DROP TABLE IF EXISTS notificacoes;
DROP TABLE IF EXISTS historicos_status;
DROP TABLE IF EXISTS ocorrencias;
DROP TABLE IF EXISTS usuarios;

CREATE TABLE usuarios (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       VARCHAR(100) NOT NULL,
  email      VARCHAR(150) NOT NULL UNIQUE,
  senha_hash VARCHAR(100) NOT NULL,
  papel      VARCHAR(255) NOT NULL
             CHECK (papel IN ('MORADOR', 'ORGAO', 'ADMIN')),
  orgao      VARCHAR(255)
             CHECK (orgao IN ('OBRAS', 'LIMPEZA_URBANA', 'ILUMINACAO_PUBLICA', 'SANEAMENTO', 'TRIAGEM')),
  criado_em  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (papel <> 'ORGAO' OR orgao IS NOT NULL)
);

CREATE TABLE ocorrencias (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo VARCHAR(255) UNIQUE,
  descricao VARCHAR(500) NOT NULL,
  categoria VARCHAR(255) NOT NULL
            CHECK (categoria IN ('BURACO', 'ILUMINACAO', 'LIXO', 'SANEAMENTO', 'CALCADA', 'PAVIMENTACAO', 'OUTROS')),
  risco     VARCHAR(255) NOT NULL DEFAULT 'NAO_CLASSIFICADO'
            CHECK (risco IN ('NAO_CLASSIFICADO', 'BAIXO', 'MEDIO', 'ALTO')),
  orgao     VARCHAR(255) NOT NULL
            CHECK (orgao IN ('OBRAS', 'LIMPEZA_URBANA', 'ILUMINACAO_PUBLICA', 'SANEAMENTO', 'TRIAGEM')),
  endereco  VARCHAR(255),
  latitude  DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
  status    VARCHAR(255) NOT NULL DEFAULT 'REGISTRADA'
            CHECK (status IN ('REGISTRADA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA')),
  criado_em TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  autor_id  BIGINT,
  FOREIGN KEY (autor_id) REFERENCES usuarios(id) ON DELETE RESTRICT
);

CREATE TABLE historicos_status (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status_anterior VARCHAR(255)
                  CHECK (status_anterior IN ('REGISTRADA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA')),
  status_novo     VARCHAR(255) NOT NULL
                  CHECK (status_novo IN ('REGISTRADA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA')),
  data_hora       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ocorrencia_id   BIGINT NOT NULL,
  autor_id        BIGINT NOT NULL,
  FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencias(id) ON DELETE RESTRICT,
  FOREIGN KEY (autor_id)      REFERENCES usuarios(id)    ON DELETE RESTRICT
);

CREATE TABLE notificacoes (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mensagem      VARCHAR(255) NOT NULL,
  data_envio    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lida          BOOLEAN NOT NULL DEFAULT FALSE,
  usuario_id    BIGINT NOT NULL,
  ocorrencia_id BIGINT NOT NULL,
  FOREIGN KEY (usuario_id)    REFERENCES usuarios(id)    ON DELETE RESTRICT,
  FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencias(id) ON DELETE RESTRICT
);
