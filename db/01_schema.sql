-- Modelo relacional derivado do diagrama de classes (PR #3).
-- Compatível com H2 (2.x) e PostgreSQL (10+).
-- Ordem: primeiro as tabelas que não dependem de ninguém.
-- =====================================================================

-- Permite rodar o script de novo no mesmo banco (ordem inversa das dependências).
DROP TABLE IF EXISTS notificacao;
DROP TABLE IF EXISTS historico_status;
DROP TABLE IF EXISTS ocorrencia;
DROP TABLE IF EXISTS usuario;
DROP TABLE IF EXISTS bairro;
DROP TABLE IF EXISTS categoria;

-- ---------------------------------------------------------------------
-- 1) Tabelas sem dependência
-- ---------------------------------------------------------------------

CREATE TABLE categoria (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(60)  NOT NULL,
    descricao  VARCHAR(200),
    CONSTRAINT uq_categoria_nome UNIQUE (nome)
);

CREATE TABLE bairro (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(80) NOT NULL,
    cidade  VARCHAR(80) NOT NULL,
    CONSTRAINT uq_bairro_nome_cidade UNIQUE (nome, cidade)
);

CREATE TABLE usuario (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    email       VARCHAR(120) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,          -- hash BCrypt, nunca a senha
    perfil      VARCHAR(15)  NOT NULL,          -- enum Perfil do diagrama
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil
        CHECK (perfil IN ('MORADOR', 'ORGAO_PUBLICO', 'ADMINISTRADOR'))
);

-- ---------------------------------------------------------------------
-- 2) Tabela central: depende de categoria, bairro, usuario e dela mesma
-- ---------------------------------------------------------------------

CREATE TABLE ocorrencia (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo                VARCHAR(20)  NOT NULL,
    descricao                VARCHAR(500) NOT NULL,          -- limite de 500 do RF03
    data_registro            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    latitude                 DECIMAL(9,6) NOT NULL,
    longitude                DECIMAL(9,6) NOT NULL,
    endereco_aproximado      VARCHAR(255),                   -- pode faltar se a geocodificação falhar
    status                   VARCHAR(15)  NOT NULL DEFAULT 'REGISTRADA',
    risco                    VARCHAR(10)  NOT NULL,          -- RF04: o risco é obrigatório
    categoria_id             INTEGER      NOT NULL,
    bairro_id                INTEGER      NOT NULL,
    usuario_id               INTEGER      NOT NULL,          -- quem registrou
    ocorrencia_principal_id  INTEGER,                        -- preenchido nos relatos repetidos (RN04)
    CONSTRAINT uq_ocorrencia_protocolo UNIQUE (protocolo),
    CONSTRAINT ck_ocorrencia_status
        CHECK (status IN ('REGISTRADA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA')),
    CONSTRAINT ck_ocorrencia_risco
        CHECK (risco IN ('BAIXO', 'MEDIO', 'ALTO')),
    CONSTRAINT ck_ocorrencia_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_ocorrencia_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_ocorrencia_nao_e_propria_principal
        CHECK (ocorrencia_principal_id IS NULL OR ocorrencia_principal_id <> id),
    CONSTRAINT fk_ocorrencia_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ocorrencia_bairro
        FOREIGN KEY (bairro_id) REFERENCES bairro (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ocorrencia_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ocorrencia_principal
        FOREIGN KEY (ocorrencia_principal_id) REFERENCES ocorrencia (id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- 3) Tabelas que dependem de ocorrencia e usuario
-- ---------------------------------------------------------------------

CREATE TABLE historico_status (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_anterior  VARCHAR(15),                            -- NULL no primeiro registro da ocorrência
    status_novo      VARCHAR(15) NOT NULL,
    data_hora        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ocorrencia_id    INTEGER     NOT NULL,
    autor_id         INTEGER     NOT NULL,                   -- quem mudou o status
    CONSTRAINT ck_historico_status_anterior
        CHECK (status_anterior IS NULL
               OR status_anterior IN ('REGISTRADA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA')),
    CONSTRAINT ck_historico_status_novo
        CHECK (status_novo IN ('REGISTRADA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA')),
    CONSTRAINT ck_historico_status_mudou
        CHECK (status_anterior IS NULL OR status_anterior <> status_novo),
    CONSTRAINT fk_historico_ocorrencia
        FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencia (id) ON DELETE CASCADE,
    CONSTRAINT fk_historico_autor
        FOREIGN KEY (autor_id) REFERENCES usuario (id) ON DELETE RESTRICT
);

CREATE TABLE notificacao (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensagem         VARCHAR(255) NOT NULL,
    data_envio       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lida             BOOLEAN      NOT NULL DEFAULT FALSE,
    ocorrencia_id    INTEGER      NOT NULL,
    destinatario_id  INTEGER      NOT NULL,
    CONSTRAINT fk_notificacao_ocorrencia
        FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencia (id) ON DELETE CASCADE,
    CONSTRAINT fk_notificacao_destinatario
        FOREIGN KEY (destinatario_id) REFERENCES usuario (id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 4) Índices nas colunas que o painel e as listas vão filtrar
-- ---------------------------------------------------------------------

CREATE INDEX idx_ocorrencia_categoria    ON ocorrencia (categoria_id);
CREATE INDEX idx_ocorrencia_bairro       ON ocorrencia (bairro_id);
CREATE INDEX idx_ocorrencia_usuario      ON ocorrencia (usuario_id);
CREATE INDEX idx_ocorrencia_status       ON ocorrencia (status);
CREATE INDEX idx_historico_ocorrencia    ON historico_status (ocorrencia_id);
CREATE INDEX idx_notificacao_destinatario ON notificacao (destinatario_id);
